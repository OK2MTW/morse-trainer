"""Morse trainer – backend (serves the frontend + API)."""
import json
from pathlib import Path

from flask import Flask, g, jsonify, request, send_from_directory

from server import admission, auth, db, site
from server.api import bp as api_bp
from server.cw import bp as cw_bp
from server.i18n import current as current_lang, t

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
VERSION = "1.1.2"
# Addresses of a particular installation are not in the code (E3): server/site.py ← /etc/morse-trainer/site.env
HOME_URL, PUBLIC_URL, PUBLIC_HOSTS = site.HOME_URL, site.PUBLIC_URL, site.PUBLIC_HOSTS

app = Flask(__name__, static_folder=None)
app.config["MAX_CONTENT_LENGTH"] = 256 * 1024
db.init_app(app)
app.register_blueprint(api_bp)
app.register_blueprint(cw_bp)


# Z-19 (0.10.19): requests that never wait for a free place (log out, report a client error, health)
ADMISSION_FREE = {"health", "api.logout", "api.logout_all", "api.client_errors_post"}


@app.before_request
def before():
    auth.check_origin()
    auth.load_session()
    # Z-19: who already trains keeps the full service; a newcomer over the limit gets 503 "full" (server/admission.py)
    if (g.user is not None and request.path.startswith("/api/") and request.endpoint not in ADMISSION_FREE
            and not admission.active.admit(g.user["id"], g.user["role"], auth.is_public())):
        return admission.busy_response()


@app.after_request
def security_headers(resp):
    if getattr(g, "refresh_cookie", None):
        auth.set_cookie(resp, g.refresh_cookie)
    # Everything is self-hosted → a strict CSP without external sources.
    resp.headers.setdefault(
        "Content-Security-Policy",
        "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; "
        "connect-src 'self'; manifest-src 'self'; worker-src 'self'; object-src 'none'; "
        "base-uri 'none'; frame-ancestors 'none'; form-action 'self'",
    )
    resp.headers.setdefault("X-Content-Type-Options", "nosniff")
    resp.headers.setdefault("Referrer-Policy", "no-referrer")
    resp.headers.setdefault("Permissions-Policy", "camera=(), geolocation=(), microphone=()")
    resp.headers.setdefault("Cross-Origin-Opener-Policy", "same-origin")
    if request.path.startswith("/api/"):
        resp.headers["Cache-Control"] = "no-store"
    return resp


@app.errorhandler(403)
def forbidden(_e):
    return jsonify(error=t("err.origin")), 403


@app.errorhandler(413)
def too_large(_e):
    return jsonify(error=t("err.tooLarge")), 413


@app.get("/api/health")
def health():
    return jsonify(status="ok", version=VERSION)


@app.get("/site-config.js")
def site_config():
    """Home and outside address for web/js/site.js (ES module, CSP 'self')."""
    js = ("// SPDX-License-Identifier: EUPL-1.2\n// Generated by the server from /etc/morse-trainer/site.env\n"
          f"export const HOME_URL = {json.dumps(HOME_URL)};\nexport const PUBLIC_URL = {json.dumps(PUBLIC_URL)};\n")
    resp = app.response_class(js, mimetype="text/javascript")
    resp.headers["Cache-Control"] = "no-cache"
    return resp


@app.get("/")
def index():
    return send_from_directory(WEB, "index.html", max_age=0)


@app.get("/<path:path>")
def static_files(path):
    if path.startswith("api/"):
        return jsonify(error=t("err.unknownApi")), 404
    if path == "manifest.webmanifest":
        return manifest()
    # The service worker must always be fresh, other files a short cache (frequent development).
    max_age = 0 if path == "sw.js" else 60
    resp = send_from_directory(WEB, path, max_age=max_age)
    if path == "sw.js":
        resp.headers["Service-Worker-Allowed"] = "/"
    return resp


def manifest():
    """Web app manifest in the user's language (lang cookie / Accept-Language). 0.8.2: the outside address is
    a separate app "Morse outside" (own name and icons)."""
    public = auth.is_public() or request.host.split(":")[0] in PUBLIC_HOSTS
    name = "manifest-venku.webmanifest" if public else "manifest.webmanifest"
    data = json.loads((WEB / name).read_text(encoding="utf-8"))
    data["name"] = t("manifest.publicName" if public else "manifest.name")
    data["short_name"] = t("manifest.publicName" if public else "manifest.shortName")
    data["description"] = t("manifest.publicDescription" if public else "manifest.description")
    data["lang"] = current_lang()
    resp = app.response_class(json.dumps(data, ensure_ascii=False, indent=2), mimetype="application/manifest+json")
    resp.headers["Cache-Control"] = "no-cache"
    resp.headers["Vary"] = "Cookie, Accept-Language"
    return resp


if __name__ == "__main__":  # development run: python -m server.app
    app.run(host="127.0.0.1", port=8080, debug=False)
